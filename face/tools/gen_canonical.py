"""Writes docscan/src/face/canonical.rs from MediaPipe's canonical face model.

The model (468 vertices in centimetres, the face looking along +z, y up, and
898 triangles with UV coordinates) is MediaPipe's
`mediapipe/modules/face_geometry/data/canonical_face_model.obj`, Apache-2.0,
Copyright Google LLC. Usage: python gen_canonical.py canonical_face_model.obj
"""
import sys
from pathlib import Path

obj = Path(sys.argv[1]).read_text().splitlines()
v = [tuple(map(float, l.split()[1:4])) for l in obj if l.startswith("v ")]
vt_raw = [tuple(map(float, l.split()[1:3])) for l in obj if l.startswith("vt ")]
corners = [[tuple(int(x) - 1 for x in p.split("/")[:2]) for p in l.split()[1:4]] for l in obj if l.startswith("f ")]
f = [tuple(c[0] for c in tri) for tri in corners]
# Texture coordinates are indexed separately from vertices: give each vertex its own.
vt = [None] * len(v)
for tri in corners:
    for vi, ti in tri:
        assert vt[vi] is None or vt[vi] == vt_raw[ti], vi
        vt[vi] = vt_raw[ti]
assert len(v) == 468 and all(t is not None for t in vt), len(v)
out = ["// Generated by face/tools/gen_canonical.py from MediaPipe's canonical face model",
       "// (mediapipe/modules/face_geometry/data/canonical_face_model.obj, Apache-2.0,",
       "// Copyright Google LLC). Do not edit.", "",
       "/// The 468 vertices of the canonical face, in centimetres: x to the face's left",
       "/// as seen by the camera (image right), y up, z towards the camera.",
       f"pub const VERTICES: [[f32; 3]; {len(v)}] = ["]
out += [f"    [{a:.6}, {b:.6}, {c:.6}]," for a, b, c in v]
out += ["];", "", "/// Texture coordinates of each vertex (u right, v up).",
        f"pub const UV: [[f32; 2]; {len(vt)}] = ["]
out += [f"    [{a:.6}, {b:.6}]," for a, b in vt]
out += ["];", "", "/// The mesh's triangles, as vertex indices.", f"pub const TRIANGLES: [[u16; 3]; {len(f)}] = ["]
out += [f"    [{a}, {b}, {c}]," for a, b, c in f]
out += ["];", ""]
dst = Path(__file__).resolve().parents[2] / "docscan/src/face/canonical.rs"
dst.write_text("\n".join(out))
print(dst, len(v), len(f))
