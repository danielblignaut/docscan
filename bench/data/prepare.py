POA_HELD = ["util_sidebar", "bank_modern", "muni_grid"]


def build_poa_dev(write: bool):
    base = DATA / "poa"
    synth, dev = base / "synth", base / "dev"
    for d in (dev,):
        if d.exists():
            shutil.rmtree(d)
    synth.mkdir(parents=True, exist_ok=True)
    # poa_synth.py --count 2000 (seed 11) renders every layout; DEV uses only the
    # held-out three, and render_one picks layout = LAYOUTS[index % 11], so render
    # just those indices with the same function (same bytes, a quarter of the time).
    code = f"""
import datetime as dt, multiprocessing as mp, poa_synth as S
S.write_places()
held = {POA_HELD!r}
idx = [i for i in range(2000) if S.LAYOUTS[i % len(S.LAYOUTS)] in held]
jobs = [(11, i, S.LAYOUTS, dt.date(2026, 10, 15), {str(synth)!r}, False) for i in idx]
with mp.Pool(8) as p:
    list(p.imap_unordered(S.render_one, jobs, chunksize=4))
print(len(jobs), "held-out pages")
"""
    py("-c", code, cwd=TESTDATA)
    py("poa_dev_claims.py", "--synth", synth, "--out", dev / "docs", cwd=TESTDATA)
    # Replace the symlinks into synth/ by copies, so synth/ can go.
    for p in (dev / "docs").glob("*.png"):
        if p.is_symlink():
            target = p.resolve()
            p.unlink()
            shutil.copy2(target, p)
    py("poa_capture.py", "--docs", dev / "docs", "--out", dev / "frames", "--seed", "4242", "--frames", "4", "--jobs", "8", cwd=TESTDATA)
    shutil.rmtree(synth)
    if write:
        write_manifest("poa_dev", suite="poa", split="dev", root=dev, files=files_under(dev, "docs/*", "frames/*"),
                       generator=gen_info([TESTDATA / f for f in ("poa_synth.py", "poa_dev_claims.py", "poa_lockbox.py", "poa_capture.py", "poa_augment.py", "augment.py")],
                                          ["poa_synth.render_one(11, i, LAYOUTS, 2026-10-15) for the held-out layouts' indices < 2000",
                                           "poa_dev_claims.py --seed 2024 --synth-seed 11", "poa_capture.py --seed 4242 --frames 4"], seed={"synth": 11, "claims": 2024, "capture": 4242}),
                       licence=SYNTHETIC + " Place names and postal codes from GeoNames (CC BY 4.0).",
                       description="Proof-of-address DEV (README, testdata/POA.md): 200 documents of the three layouts held out of training, "
                       "100 genuine and 25 of each negative case, each a burst of 4 camera frames.")


