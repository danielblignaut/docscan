def select(suite: str, split: str, names: list[str] | None) -> list[str]:
    if names:
        return names
    out = []
    suites = suite.split(",")
    for n, (s, sp, _) in SETS.items():
        if "all" not in suites and s not in suites:
            continue
        if split != "both" and sp not in (split, "both"):
            continue
        out.append(n)
    return out


def ensure(name: str, write: bool, verify_only: bool, quick_files=None) -> bool:
    for dep in DEPENDS.get(name, []):
        ensure(dep, False, verify_only)
    has = (MANIFESTS / f"{name}.json").exists()
    if has and not write:
        ok, msg = verify_manifest(name, quick_files)
        if ok:
            log("ok  ", msg)
            return True
        log("MISS", msg)
        if verify_only:
            return False
    elif verify_only:
        log("MISS", f"{name}: no manifest")
        return False
    log(f"build {name}")
    SETS[name][2](write or not has)
    ok, msg = verify_manifest(name, quick_files)
    log("ok  " if ok else "FAIL", msg)
    if not ok:
        raise SystemExit(f"{name} regenerated to different bytes than its manifest: see bench/README.md (Datasets)")
    return ok


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sets", help="comma-separated set names (default: by --suite and --split)")
    ap.add_argument("--suite", default="all")
    ap.add_argument("--split", default="both")
    ap.add_argument("--write-manifests", action="store_true")
    ap.add_argument("--verify-only", action="store_true")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    names = select(a.suite, a.split, a.sets.split(",") if a.sets else None)
    if a.list:
        for n in names:
            m = manifest(n) if (MANIFESTS / f"{n}.json").exists() else {}
            print(f"{n:22} {SETS[n][0]:8} {SETS[n][1]:5} {m.get('count', '-'):>6} files {m.get('bytes', 0) / 1e6:9.1f} MB")
        return
    bad = [n for n in names if not ensure(n, a.write_manifests, a.verify_only)]
    if bad:
        raise SystemExit(f"not ready: {bad}")


if __name__ == "__main__":
    main()
