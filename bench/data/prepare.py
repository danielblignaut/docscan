"""Materialises every benchmark set under $BENCH_DATA (default
/tmp/docscan-bench) and checks it against its manifest in bench/manifests/.

  python bench/data/prepare.py [--sets a,b] [--suite id|barcode|poa|face|all] [--split dev|test|both]
                               [--write-manifests] [--verify-only]

For each set: if its files are present and match the manifest (sha256 of
every file), nothing is done; otherwise it is (re)generated with the repo's
own generators (or downloaded, for public data) and checked again. A set that
regenerates to different bytes is an error: the generator, a library version
(bench/requirements.txt) or a download changed, and every number measured on
the old bytes is no longer comparable. `--write-manifests` (re)writes the
manifests from what is on disk; do that only when deliberately creating a new
version of a set, in its own commit.

No image, video, face or dataset ever goes into the repository: the manifests
hold file names, hashes, sizes, generators, seeds and licences only.
"""
