VENV_PKGS = (ROOT / "bench" / "requirements.txt").read_text().split()


def py(*args, cwd=None, env=None):
    log("  $", "python", *map(str, args))
    subprocess.run([str(PY), *map(str, args)], cwd=cwd, check=True, env={**os.environ, **(env or {})})


def gen_info(scripts: list[Path], args: list, seed=None, **kw) -> dict:
    return {"scripts": [str(s.relative_to(ROOT)) for s in scripts], "scripts_sha256": safe_digest(code_sha256(scripts)),
            "args": [str(a) for a in args], "seed": seed, "python_packages": VENV_PKGS, **kw}


def files_under(root: Path, *globs: str) -> list[Path]:
    out = []
    for g in globs:
        out += [p for p in root.glob(g) if p.is_file()]
    return sorted(set(out))


