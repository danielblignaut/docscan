"""Generate offline parsing metadata from the pinned Apache-2.0 GS1 dictionary."""
import hashlib,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
source=json.loads((HERE/'source.json').read_text())
raw=(HERE/'gs1-syntax-dictionary.txt').read_bytes()
assert hashlib.sha256(raw).hexdigest()==source['files']['gs1-syntax-dictionary.txt']
records={}
for line in raw.decode().splitlines():
 if not line or line.startswith('#'):continue
 body,_,title=line.partition('#'); tokens=body.split()
 if not tokens:continue
 ai=tokens.pop(0);flags=''
 if tokens and not re.match(r'\[?[NXYZ]',tokens[0]):flags=tokens.pop(0)
 components=[]
 while tokens and re.match(r'\[?[NXYZ]',tokens[0]):
  token=tokens.pop(0);m=re.fullmatch(r'(\[?)([NXYZ])(\.\.)?(\d+)(\]?)(?:,(.*))?',token)
  if not m:raise ValueError(token)
  optional,kind,var,length,_,linters=m.groups();n=int(length)
  components.append({'kind':kind,'min':1 if var else n,'max':n,'optional':bool(optional),'linters':linters.split(',') if linters else []})
 attributes={}
 for t in tokens:
  k,sep,v=t.partition('=');attributes.setdefault(k,[]).append(v if sep else '')
 if '-' in ai:
  lo,hi=ai.split('-');ais=[str(i).zfill(len(lo)) for i in range(int(lo),int(hi)+1)]
 else:ais=[ai]
 for key in ais:
  records[key]={'title':title.strip(),'predefined':'*' in flags,'digitalAttribute':'?' in flags,'components':components,'attributes':attributes}
text='// Generated by scripts/gs1/generate.py. Do not edit.\n// Derived from GS1 Barcode Syntax Dictionary, copyright GS1 AISBL, Apache-2.0.\n// Local transformation into TypeScript metadata; see scripts/gs1/LICENSE and source.json.\n'
text+='export const GS1_DICTIONARY_REVISION = '+json.dumps(source['revision'])+';\n'
text+='export const GS1_DICTIONARY: Record<string, { title: string; predefined: boolean; digitalAttribute: boolean; components: { kind: string; min: number; max: number; optional: boolean; linters: string[] }[]; attributes: Record<string,string[]> }> = '+json.dumps(records,separators=(',',':'),ensure_ascii=False)+';\n'
(ROOT/'demo/src/gs1/dictionary.ts').write_text(text)
print(f'Generated {len(records)} AI definitions from {source["revision"]}')
