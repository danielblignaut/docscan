#!/usr/bin/env python3
"""Freeze the reference's transcendental arithmetic as exact tables for Rust.

`optics.linear` of every code, OpenCV's float32 Gaussian kernel (73 taps,
sigma 9), and `optics.encode` as 255 thresholds: for each code k >= 1, the
bit pattern of the smallest float32 in [0, 1] that numpy encodes to >= k. The
thresholds come from evaluating `optics.encode` on EVERY float32 in [0, 1]
(about 1.07e9 values, in chunks) and the script fails unless the reference is
monotone. Rust then needs no powf/exp, so native and WASM agree to the byte.
Prints the Rust source of the tables; writes nothing.
"""
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]/'research_optics'))
from optics import linear, encode  # noqa: E402


def thresholds():
    one = int(np.float32(1).view(np.uint32))
    found = np.full(256, -1, np.int64)
    found[0] = 0
    last = 0
    step = 1 << 24
    for start in range(0, one+1, step):
        bits = np.arange(start, min(start+step, one+1), dtype=np.uint32)
        codes = encode(bits.view(np.float32)).astype(np.int64)
        if codes[0] < last or np.any(np.diff(codes) < 0):
            raise ValueError('reference encode is not monotone')
        for k in np.unique(codes):
            if found[k] < 0:
                found[k] = int(bits[np.argmax(codes >= k)])
        last = int(codes[-1])
    if np.any(found < 0):
        raise ValueError('some code never produced')
    return found[1:]


def rust(name, kind, values):
    rows = [', '.join(f'0x{int(v):08x}' for v in values[i:i+8]) for i in range(0, len(values), 8)]
    return f'const {name}: [{kind}; {len(values)}] = [\n' + ''.join(f'    {r},\n' for r in rows) + '];\n'


def main():
    lin = linear(np.arange(256, dtype=np.uint8)).astype(np.float32).view(np.uint32)
    kernel = cv2.getGaussianKernel(73, 9, ktype=cv2.CV_32F).ravel().view(np.uint32)
    print('// Generated by experiments/research_optics_native/tables.py from the frozen')
    print(f'// reference (numpy {np.__version__}, OpenCV {cv2.__version__}); do not edit.')
    print(rust('LINEAR_BITS', 'u32', lin))
    print(rust('GAUSSIAN_BITS', 'u32', kernel))
    print(rust('ENCODE_THRESHOLD_BITS', 'u32', thresholds()))


if __name__ == '__main__':
    main()
